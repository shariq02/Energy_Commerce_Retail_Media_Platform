from __future__ import annotations

from pathlib import Path

from ai.knowledge_quality import acceptance, runs, state, thresholds
from ai.knowledge_quality.evaluation import HYBRID_GRAPH
from scripts.knowledge import _unit_common as uc


def findings_path(root: Path, corpus_id: str) -> Path:
    return root / "src" / "findings" / "knowledge_findings" / f"{corpus_id}_quality.md"


def table(headers: list[str], rows: list[list]) -> str:
    head = "| " + " | ".join(headers) + " |\n|" + "---|" * len(headers) + "\n"
    return head + "".join(
        "| " + " | ".join(str(c) for c in row) + " |\n" for row in rows
    )


def share(count: int, total: int) -> str:
    return f"{count}/{total} ({100 * count / total:.0f}%)" if total else "n/a"


def metric_rows(groups: dict, prefix: str | None) -> list[list]:
    rows = []
    for name, by_mode in groups.items():
        if prefix is None and name != "all":
            continue
        if prefix and not name.startswith(prefix):
            continue
        for mode, m in by_mode.items():
            n = m["positive"]
            rows.append(
                [
                    name.split(":", 1)[-1],
                    mode,
                    n,
                    share(m["recall_1"], n),
                    share(m["recall_5"], n),
                    share(m["recall_context"], n),
                    f"{m['mrr_sum'] / n:.3f}" if n else "n/a",
                    f"{m['ndcg_5_sum'] / n:.3f}" if n else "n/a",
                    share(m["no_match"], m["negative"]),
                ]
            )
    return rows


METRIC_HEADERS = [
    "group",
    "type",
    "positive",
    "Recall@1",
    "Recall@5",
    "Recall@context",
    "MRR",
    "nDCG@5",
    "negatives no_match",
]


def run_section(run: dict | None, title: str) -> str:
    if run is None:
        return f"## {title}\n\nNo run recorded.\n\n"
    out = f"## {title}\n\n### run context\n\n"
    ctx = [
        ["run id", run["run_id"]],
        ["created", run["created"]],
        ["build id", run["build_id"]],
        ["collection", run["collection"]],
        ["retrieval config version", run["config_version"]],
        [
            "question set",
            (
                f"version {run['question_set']['version']}, "
                f"{run['question_set']['questions']} questions, "
                f"hash {run['question_set']['hash'][:12]}"
            ),
        ],
        ["config", ", ".join(f"{k}={v}" for k, v in sorted(run["config"].items()))],
        ["extra dense collections", run.get("extra_collections") or "none"],
        ["reranker scores missing", run.get("rerank_missing", 0)],
        ["judge", run.get("judge") or "not used"],
    ]
    out += table(["item", "value"], ctx) + "\n### overall\n\n"
    out += table(METRIC_HEADERS, metric_rows(run["metrics"], None)) + "\n"
    out += "### per unit kind\n\n"
    out += table(METRIC_HEADERS, metric_rows(run["metrics"], "kind:")) + "\n"
    out += "### per query class\n\n"
    out += table(METRIC_HEADERS, metric_rows(run["metrics"], "class:")) + "\n"
    flags = []
    for o in run["outcomes"]:
        got = o["served"][HYBRID_GRAPH]
        if o["expected_unit_id"] and (o["ranks"][HYBRID_GRAPH] or 99) > 5:
            flags.append(
                [o["question_id"], "missed", o["expected_unit_id"], ", ".join(got[:3])]
            )
        if not o["expected_unit_id"] and got:
            flags.append(
                [o["question_id"], "negative answered", "", ", ".join(got[:3])]
            )
    out += "### flags\n\n"
    out += (
        table(["question", "flag", "expected unit", "served (first 3)"], flags)
        if flags
        else "None.\n"
    )
    return out + "\n"


def render(ai_dir: Path, corpus_id: str) -> str:
    check = runs.load_check(ai_dir, corpus_id)
    tune = runs.latest_run(ai_dir, corpus_id, "tune")
    holdout = runs.latest_run(ai_dir, corpus_id, "holdout")
    base = runs.latest_run(ai_dir, corpus_id, "base")
    accepted = state.read(ai_dir, corpus_id)
    out = f"# {corpus_id.upper()} RETRIEVAL QUALITY FINDINGS\n\n"
    out += (
        "_Auto-generated by `ai/knowledge_quality`. The designation of a build belongs "
        "to the owner; a candidate that fails a check cannot be designated._\n\n"
    )
    out += "## checks\n\n"
    if check is None:
        out += "No check recorded.\n\n"
    else:
        integrity, fresh = check["integrity"], check["freshness"]
        rows = [
            [
                "integrity",
                "PASS" if not integrity["problems"] else "FAIL",
                "; ".join(integrity["problems"]) or "all checks pass",
            ]
        ]
        rows.append(
            [
                "units added since designation",
                len(integrity["added"]),
                ", ".join(integrity["added"][:5]),
            ]
        )
        rows.append(
            [
                "units removed since designation",
                len(integrity["removed"]),
                ", ".join(integrity["removed"][:5]),
            ]
        )
        rows.append(
            [
                "units changed since designation",
                len(integrity["changed"]),
                ", ".join(integrity["changed"][:5]),
            ]
        )
        rows.append(["notes", len(integrity["notes"]), "; ".join(integrity["notes"])])
        rows.append(["sources checked", fresh["checked"], ""])
        rows.append(
            [
                "stale units",
                len(fresh["stale"]),
                ", ".join(sorted({s["unit_id"] for s in fresh["stale"]})[:8]),
            ]
        )
        rows.append(
            [
                "unchecked sources",
                len(fresh["unchecked"]),
                ", ".join(sorted({s["source"] for s in fresh["unchecked"]})[:5]),
            ]
        )
        rows.append(["snapshot", "", fresh["snapshot"] or ""])
        out += (
            f"_Check made: {check['created']}_\n\n"
            + table(["check", "result", "details"], rows)
            + "\n"
        )
    out += run_section(tune, "tuning questions")
    out += "## thresholds\n\n"
    found = thresholds.versions(ai_dir, corpus_id)
    if not found:
        out += "No retrieval config version written.\n\n"
    else:
        data = thresholds.read_version(ai_dir, corpus_id, found[-1])
        rows = []
        for name, t in data["thresholds"].items():
            goals = "no conflict"
            if t["conflict"]:
                goals = "CONFLICT: the owner decides"
            elif t.get("set_by") == "owner":
                goals = f"set by the owner (rule: {t.get('computed_threshold')})"
            elif t.get("set_by") == "search":
                goals = f"found by the search (rule: {t.get('computed_threshold')})"
            rows.append(
                [
                    name,
                    t["threshold"],
                    share(t["hits_kept"], t["expected_hits"]),
                    share(t["negatives_no_match"], t["negatives"]),
                    goals,
                ]
            )
        out += f"Config version {data['version']}, tuning run {data.get('tuning_run_id')}.\n\n"
        out += (
            table(
                [
                    "retriever",
                    "threshold",
                    "expected hits kept",
                    "negatives no_match",
                    "goals",
                ],
                rows,
            )
            + "\n"
        )
        hybrid = next(
            (v["hybrid"] for v in data["thresholds"].values() if v.get("hybrid")), None
        )
        if hybrid:
            out += (
                f"Hybrid with these thresholds on the tuning questions: {hybrid['hits']} of "
                f"{hybrid['hits_without_thresholds']} hits kept, "
                f"{hybrid['negatives_no_match']} negative questions no_match.\n\n"
            )
    out += run_section(holdout, "holdout questions")
    out += run_section(
        base, "older questions with the stack of the candidate (seen data)"
    )
    out += "## acceptance\n\n"
    event = accepted["designated"]
    if event is None:
        out += "No build is designated.\n\n"
    else:
        rows = [
            [
                c["check"],
                {True: "PASS", False: "FAIL", None: "n/a"}[c["passed"]],
                c["detail"],
            ]
            for c in event["checks"]
        ]
        out += (
            f"Designated: build {event['build_id']} on {event['designated_on']}, approved by "
            f"{event['approver']}, evaluation run {event['evaluation_run_id']}, event "
            f"{event['event_hash'][:12]}.\n\n"
        )
        out += table(["check", "result", "detail"], rows) + "\n"
    out += f"Rule: {acceptance.MODE}, positive {acceptance.POSITIVE_RATE:.2f}, negative {acceptance.NEGATIVE_RATE:.2f}, extra misses at most {acceptance.MAX_EXTRA_MISSES}.\n"
    return out


def export(ai_dir: Path, root: Path, corpus_id: str) -> Path:
    path = findings_path(root, corpus_id)
    uc.write_text(path, render(ai_dir, corpus_id))
    return path
