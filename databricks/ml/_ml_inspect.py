# DBTITLE 1,Common inspection


def inspect_ml_table(
    df_after: DataFrame,
    table: str,
    *,
    ecosystem: str,
    key_cols: list[str] | None = None,
    df_before: DataFrame | None = None,
    partition_col: str | None = None,
    target_col: str | None = None,
) -> list:
    """Schema, volume, grain, per-column null rate, forbidden columns and, when
    the frame carries a partition, rows and target coverage per partition."""
    rows: list[tuple] = []
    full = ml_fqn(table, ecosystem)
    cols = df_after.columns

    def add(category, name, metric, observed, expected, status, severity, details=""):
        rows.append(
            (category, name, metric, observed, expected, status, severity, details)
        )

    add("schema", "column_count", "count", float(len(cols)), None, "INFO", "INFO")
    bad = [c for c in cols if c in CLASS_E_COLUMNS]
    add(
        "schema",
        "class_e_columns",
        "count",
        float(len(bad)),
        0.0,
        "PASS" if not bad else "FAIL",
        "INFO" if not bad else "CRITICAL",
        f"columns={bad}",
    )
    n_after = df_after.count()
    add("volume", "row_count", "rows", float(n_after), None, "INFO", "INFO")
    if df_before is not None:
        n_before = df_before.count()
        add(
            "volume",
            "input_output_reconciliation",
            "row_delta",
            float(n_after - n_before),
            float(n_before),
            "INFO",
            "INFO",
            f"before={n_before} after={n_after}",
        )
    if key_cols:
        dup_n = df_after.groupBy(*key_cols).count().filter(F.col("count") > 1).count()
        add(
            "grain",
            "duplicate_keys",
            "count",
            float(dup_n),
            0.0,
            "PASS" if dup_n == 0 else "FAIL",
            "INFO" if dup_n == 0 else "CRITICAL",
            f"key_cols={key_cols}",
        )
    rates = null_rates(df_after, cols)
    for c in cols:
        add(
            "completeness",
            f"null_rate:{c}",
            "null_rate",
            rates[c],
            None,
            "INFO",
            "INFO",
        )
    if partition_col and partition_col in cols:
        agg = [F.count("*").alias("n")]
        if target_col and target_col in cols:
            agg += [
                F.count(target_col).alias("target_n"),
                F.expr(f"avg(try_cast(`{target_col}` AS DOUBLE))").alias("target_mean"),
            ]
        for r in df_after.groupBy(partition_col).agg(*agg).collect():
            d = r.asDict()
            add(
                "partitions",
                f"partition:{d[partition_col]}",
                "rows",
                float(d["n"]),
                None,
                "INFO",
                "INFO",
                f"target_n={d.get('target_n')} target_mean={d.get('target_mean')}",
            )

    by_cat: dict[str, list] = {}
    for cat, name, metric, obs, exp, status, sev, details in rows:
        by_cat.setdefault(cat, []).append(
            (name, metric, obs, exp, status, sev, details)
        )
    blocks = []
    for cat in sorted(by_cat):
        table_md = [
            "| check | metric | observed | expected | status | severity | details |",
            "|---|---|---|---|---|---|---|",
        ]
        for name, metric, obs, exp, status, sev, details in by_cat[cat]:
            table_md.append(
                f"| {name} | {metric} | {obs if obs is not None else ''} | "
                f"{exp if exp is not None else ''} | {status} | {sev} | {details} |"
            )
        blocks.append((cat, "\n".join(table_md)))
    print(f"inspected {full}: {n_after} rows, {len(cols)} columns")
    return blocks


