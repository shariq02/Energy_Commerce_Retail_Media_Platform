# DBTITLE 1,Findings export (src/findings/ml_findings/<source>.md)


def _ml_findings_dir():
    d = _os.path.join(repo_root(), "src", "findings", "ml_findings")
    _os.makedirs(d, exist_ok=True)
    return d


ML_STALE_AFTER_HOURS = 24
_ML_GEN_PAT = _re.compile(r"_Generated: (\d{4}-\d\d-\d\dT\d\d:\d\dZ)_")


def _mark_ml_stale(block: str, now) -> str:
    if "> STALE" in block:
        return block
    m = _ML_GEN_PAT.search(block)
    if m:
        gen = _dt.datetime.strptime(m.group(1), "%Y-%m-%dT%H:%MZ").replace(
            tzinfo=_dt.UTC
        )
        if now - gen <= _dt.timedelta(hours=ML_STALE_AFTER_HOURS):
            return block
    head, _, rest = block.partition("\n## ")
    title, _, tail = rest.partition("\n")
    return (
        f"{head}\n## {title}\n\n"
        f"> STALE: not rewritten in the last {ML_STALE_AFTER_HOURS}h\n{tail}"
    )


def write_ml_findings(
    source: str, notebook_key: str, section_title: str, blocks: list
) -> None:
    d = _ml_findings_dir()
    md = _os.path.join(d, source + ".md")
    now = _dt.datetime.now(tz=_dt.UTC)
    lines = [
        f"<!-- BEGIN {source}:{notebook_key} -->",
        f"## {section_title}",
        "",
        f"_Generated: {now.strftime('%Y-%m-%dT%H:%MZ')}_",
        "",
    ]
    for heading, body in blocks:
        if body is None or str(body).strip() == "":
            continue
        lines += [f"### {heading}", "", str(body).rstrip(), ""]
    lines.append(f"<!-- END {source}:{notebook_key} -->")
    block = "\n".join(lines)
    existing = ""
    if _os.path.exists(md):
        with open(md, encoding="utf-8") as fh:
            existing = fh.read()
    pat = _re.compile(
        r"<!-- BEGIN "
        + _re.escape(source)
        + r":([\w.\-]+) -->.*?<!-- END "
        + _re.escape(source)
        + r":\1 -->",
        _re.DOTALL,
    )
    kept = {
        mm.group(1): _mark_ml_stale(mm.group(0), now) for mm in pat.finditer(existing)
    }
    kept[notebook_key] = block
    intro = (
        "_Auto-generated by the ML notebooks (`databricks/ml/`). "
        "One `## ` section per (notebook, table); re-running a notebook "
        "replaces its own sections, other sections are preserved and marked "
        "STALE once older than 24h._"
    )
    header = f"# {source.upper()} ML FINDINGS\n\n{intro}\n\n"
    body_out = "\n\n".join(kept[k] for k in sorted(kept))
    out = header + body_out + "\n"
    tmp = md + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write(out)
    _os.replace(tmp, md)
    print(f"findings export -> {md}  ('{notebook_key}', {len(kept)} section(s))")


